def lang() -> str:
    return st.session_state.get("ui_lang", "en")


def t(key: str) -> str:
    return TEXT.get(lang(), TEXT["en"]).get(key, TEXT["en"].get(key, key))


def language_selector() -> None:
    """Language switch with flag images (emoji flags fail on Windows)."""
    st.markdown(f'<p class="lang-label">{t("language")}</p>', unsafe_allow_html=True)
    current = st.session_state.get("ui_lang", "en")
    c1, c2 = st.columns(2)
    with c1:
        st.markdown(
            '<div class="lang-btn-wrap">'
            '<img src="https://flagcdn.com/w40/gb.png" width="22" height="16" alt="EN"/> '
            "<b>English</b></div>",
            unsafe_allow_html=True,
        )
        if st.button(
            "English",
            key="lang_btn_en",
            use_container_width=True,
            type="primary" if current == "en" else "secondary",
        ):
            st.session_state["ui_lang"] = "en"
            st.rerun()
    with c2:
        st.markdown(
            '<div class="lang-btn-wrap">'
            '<img src="https://flagcdn.com/w40/fr.png" width="22" height="16" alt="FR"/> '
            "<b>Français</b></div>",
            unsafe_allow_html=True,
        )
        if st.button(
            "Français",
            key="lang_btn_fr",
            use_container_width=True,
            type="primary" if current == "fr" else "secondary",
        ):
            st.session_state["ui_lang"] = "fr"
            st.rerun()
